// Generates supabase/seed.sql from the templates defined in survey-core.
// Run: npm run gen:seed
import { writeFileSync } from 'node:fs';
import { TEMPLATES } from '../packages/survey-core/src/index.ts';

const lit = (s: unknown) => `'${String(s).replace(/'/g, "''")}'`;
const rows = TEMPLATES.map((t) =>
  `(${lit(t.key)}, ${lit(t.title)}, ${lit(t.description)}, ${lit(t.category)}, ${lit(JSON.stringify(t.schema))}::jsonb, ${lit(JSON.stringify(t.theme ?? {}))}::jsonb, ${lit(JSON.stringify(t.settings ?? {}))}::jsonb, 'system')`);
const sql = `-- AUTO-GENERATED by scripts/gen-seed.ts — do not edit by hand.
insert into public.survey_templates (key, title, description, category, schema_json, theme_json, settings_json, visibility) values
${rows.join(',\n')}
on conflict (key) do update set title = excluded.title, description = excluded.description, category = excluded.category,
  schema_json = excluded.schema_json, theme_json = excluded.theme_json, settings_json = excluded.settings_json;
`;
writeFileSync('supabase/seed.sql', sql);
console.log(`seed.sql written (${TEMPLATES.length} templates)`);
